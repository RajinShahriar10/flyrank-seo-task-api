-- One schema file, used by Postgres on first volume creation AND by the app on startup.
CREATE TABLE IF NOT EXISTS tasks (
    id INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    title TEXT NOT NULL,
    done BOOLEAN NOT NULL DEFAULT FALSE,
    created_at TIMESTAMPTZ NOT NULL DEFAULT CURRENT_TIMESTAMP,
    updated_at TIMESTAMPTZ NOT NULL DEFAULT CURRENT_TIMESTAMP
);

CREATE INDEX IF NOT EXISTS idx_tasks_done ON tasks(done);
CREATE INDEX IF NOT EXISTS idx_tasks_title ON tasks(title);

-- Seed three example jobs only when the table is empty.
INSERT INTO tasks (id, title, done)
SELECT seed.id, seed.title, seed.done
FROM (VALUES
    (1, 'Audit /pricing for broken links', FALSE),
    (2, 'Generate sitemap for /blog', TRUE),
    (3, 'Check meta titles on /docs', FALSE)
) AS seed(id, title, done)
WHERE NOT EXISTS (SELECT 1 FROM tasks);

-- Keep the identity sequence ahead of the explicit seed ids.
SELECT setval(
    pg_get_serial_sequence('tasks', 'id'),
    GREATEST((SELECT COALESCE(MAX(id), 1) FROM tasks), 1)
);
